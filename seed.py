def seed():
    with app.app_context():
        print('Создание таблиц...')
        db.create_all()

        # Admin user
        if not User.query.filter_by(email='admin@blockstop.ru').first():
            admin = User(
                full_name='Администратор',
                email='admin@blockstop.ru',
                phone='8 917 837-37-52',
                role='admin',
                company_name='ООО «МИР ПОЖАРНОЙ БЕЗОПАСНОСТИ»',
                inn='3460083690',
            )
            admin.set_password('admin123')
            db.session.add(admin)
            print('✓ Администратор создан: admin@blockstop.ru / admin123')
        else:
            print('  Администратор уже существует')

        # Categories
        cat_map = {}
        for name, slug, desc, icon, order in CATEGORIES:
            cat = Category.query.filter_by(slug=slug).first()
            if not cat:
                cat = Category(name=name, slug=slug, description=desc, icon=icon, sort_order=order)
                db.session.add(cat)
                print(f'✓ Категория: {name}')
            cat_map[slug] = cat
        db.session.flush()

        # Refresh cat_map with IDs
        for slug in cat_map:
            cat_map[slug] = Category.query.filter_by(slug=slug).first()

        # Products
        for (name, cat_slug, desc, price, unit, in_stock, featured) in PRODUCTS:
            if not Product.query.filter_by(name=name).first():
                cat = cat_map.get(cat_slug)
                if not cat:
                    print(f'  ! Категория не найдена: {cat_slug}')
                    continue
                p = Product(
                    name=name,
                    category_id=cat.id,
                    description=desc,
                    price=price,
                    unit=unit,
                    in_stock=in_stock,
                    featured=featured,
                )
                db.session.add(p)
                print(f'  + {name}')

        db.session.commit()
        print('\n✅ Данные успешно загружены!')
        print('\nЗайдите в админку:')
        print('  URL:   /admin/')
        print('  Email: admin@blockstop.ru')
        print('  Пароль: admin123')


